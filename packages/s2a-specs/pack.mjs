#!/usr/bin/env node
// pack.mjs — collect the published shape of @adobecom/s2a-specs into dist/.
//
// The canonical artifacts live beside each component (packages/components/src/
// <slug>/<slug>.contract.json), because that is where `npm run specs:build`
// writes them and where the freshness gate compares them. A consumer should not
// have to know that layout, so this gathers them into one flat tree:
//
//   dist/contracts/<slug>.json     the interop contract (southleft shape)
//   dist/catalog/<slug>.json       the light index entry
//   dist/index.json                every component, with what it has
//   dist/contract.schema.json      the schema the contracts validate against
//   dist/index.mjs                 a small loader so consumers can require nothing
//
// Build tooling (build.mjs, scaffold.mjs, the engine and adapters) is NOT
// shipped. Consumers read contracts; they do not regenerate them.
//
//   node packages/s2a-specs/pack.mjs            (npm run pack:dist, and prepack)
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..", "..");
const SRC = join(ROOT, "packages", "components", "src");
// The transform lives next door: it owns the contracts index and the vendored
// schema. This package only gathers and publishes what that transform emitted.
const TRANSFORM = join(ROOT, "packages", "spec-dictionary");
const DIST = join(__dirname, "dist");

const read = (p) => JSON.parse(readFileSync(p, "utf8"));
const write = (p, data) => {
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, typeof data === "string" ? data : JSON.stringify(data, null, 2) + "\n");
};

rmSync(DIST, { recursive: true, force: true });

// 1. contracts + catalogs, flattened by slug
const slugs = readdirSync(SRC).filter((d) => existsSync(join(SRC, d, `${d}.contract.json`))).sort();
const shipped = [];
for (const slug of slugs) {
  const contract = read(join(SRC, slug, `${slug}.contract.json`));
  write(join(DIST, "contracts", `${slug}.json`), contract);
  const catalogPath = join(SRC, slug, `${slug}.catalog.json`);
  const catalog = existsSync(catalogPath) ? read(catalogPath) : null;
  if (catalog) write(join(DIST, "catalog", `${slug}.json`), catalog);
  shipped.push({ slug, name: contract.name, version: contract.version ?? null, catalog: Boolean(catalog) });
}

// 2. the index — every component we describe, and whether it has a contract yet.
// Shipping the gap deliberately: a consumer can see what is covered and what is
// still only a hand-written spec, rather than discovering it by a 404.
const indexPath = join(TRANSFORM, "out", "contracts.index.json");
const full = existsSync(indexPath) ? read(indexPath) : { items: [] };
const contracted = new Set(shipped.map((s) => s.slug));
write(join(DIST, "index.json"), {
  generatedAt: new Date().toISOString(),
  counts: { described: full.items.length, contracted: shipped.length },
  contracts: shipped,
  described: full.items.map((i) => ({ slug: i.slug, name: i.name, contracted: contracted.has(i.slug) })),
});

// 3. the schema the contracts conform to
write(join(DIST, "contract.schema.json"), read(join(TRANSFORM, "southleft", "contract.schema.json")));

// 4. a loader, so a consumer never has to know the file layout
write(join(DIST, "index.mjs"), `// generated by pack.mjs — do not edit
import { readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DIR = dirname(fileURLToPath(import.meta.url));
const read = (p) => JSON.parse(readFileSync(p, "utf8"));

/** Every component S2A describes, and whether it has a contract yet. */
export const index = read(join(DIR, "index.json"));

/** The JSON Schema every contract validates against. */
export const schema = read(join(DIR, "contract.schema.json"));

/** Slugs that have a contract. */
export function listContracts() {
  return index.contracts.map((c) => c.slug);
}

/** One component's contract, or null when it has no contract yet. */
export function getContract(slug) {
  const p = join(DIR, "contracts", slug + ".json");
  return existsSync(p) ? read(p) : null;
}

/** One component's catalog entry — the cheap version, for listing and picking. */
export function getCatalog(slug) {
  const p = join(DIR, "catalog", slug + ".json");
  return existsSync(p) ? read(p) : null;
}

export default { index, schema, listContracts, getContract, getCatalog };
`);

console.log(`packed ${shipped.length} contract(s) of ${full.items.length} described component(s)`);
for (const s of shipped) console.log(`  ${s.slug.padEnd(24)} ${s.name}${s.catalog ? "" : "  (no catalog)"}`);
