#!/usr/bin/env node
// render.mjs — one contract, many implementations.
//
//   npm run specs:render -- --slug=button                 every target
//   npm run specs:render -- --slug=button --target=milo   just one
//   npm run specs:render -- --all --target=lit
//   npm run specs:render -- --slug=button --check         fail if stale, write nothing
//
// The contract is the only input. Each target decides what files it needs and
// where they go, so the two never collide: Lit output lands in Storybook's
// generated/ folder, Milo output in packages/milo-blocks/. Neither touches the
// hand-written components in packages/components/src.
import { existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildOne, ROOT } from "./build.mjs";
import { renderers, targets } from "./lib/renderers/index.mjs";
import { SYSTEMS, buildOpts, slugsOf } from "./systems.mjs";
import { tokenSubset, subsetCss } from "./lib/token-subset.mjs";
import { looksOf, trimToLooks } from "./lib/milo-trim.mjs";

// A composed child is rendered through its own contract. Resolved by slug or by
// the name a contract carries (slot.accepts says "Button"; the file is
// button.contract.json), from the contracts beside the components.
function contractsOf(dir) {
  const out = [];
  for (const d of existsSync(dir) ? readdirSync(dir) : []) {
    const f = join(dir, d, `${d}.contract.json`);
    if (!existsSync(f)) continue;
    try {
      const c = JSON.parse(readFileSync(f, "utf8"));
      const defsFile = join(dir, d, `${d}.defs.json`);
      const defs = existsSync(defsFile) ? JSON.parse(readFileSync(defsFile, "utf8")) : {};
      out.push({ slug: d, name: c.name ?? c.component?.name ?? d, props: c.props ?? [], archetype: c.archetype ?? null, tier: defs.tier ?? null });
    } catch { /* unreadable: not a contract */ }
  }
  return out;
}
const alnumKey = (x) => String(x ?? "").toLowerCase().replace(/[^a-z0-9]/g, "");

const SRC = join(ROOT, "packages", "components", "src");
const arg = (k) => process.argv.find((a) => a.startsWith(`--${k}=`))?.slice(k.length + 3);
const has = (f) => process.argv.includes(`--${f}`);

// Which design system. Ours renders through lit + milo; a shipped library
// (--system=spectrum) renders through `upstream`, which mounts its element.
const system = SYSTEMS[arg("system") ?? "s2a"];
if (!system) { console.error(`unknown system: ${arg("system")}\nknown: ${Object.keys(SYSTEMS).join(", ")}`); process.exit(2); }
const ownTargets = system.id === "s2a" ? targets.filter((t) => t !== "upstream") : [system.storybook.renderer];
const wanted = (arg("target") ?? "all").split(",").map((s) => s.trim());
const chosen = wanted.includes("all") ? ownTargets : wanted;
const unknown = chosen.filter((t) => !renderers[t]);
if (unknown.length) {
  console.error(`unknown target(s): ${unknown.join(", ")}\nknown: ${targets.join(", ")}`);
  process.exit(2);
}

const slugs = has("all") ? slugsOf(system) : [arg("slug")].filter(Boolean);

// Slots resolve inside the contract's own system: Spectrum's card composes
// Spectrum's button, never ours of the same name.
const contractIndex = contractsOf(system.src);
const contractFor = (key) => contractIndex.find((c) => c.slug === key || alnumKey(c.name) === alnumKey(key) || alnumKey(c.slug) === alnumKey(key)) ?? null;

// A shipped library rendered for Milo carries its own tokens: only what it uses.
const tokenFiles = system.id !== "s2a" ? system.tokens().files : null;

const miloBuild = (s) => buildOne(s, buildOpts(system)).ir;
const childSlots = (node, self) => (node.anatomy.parts ?? []).flatMap((part) => (part.slot?.accepts ?? [])
  .map((a) => (a.startsWith("kind:") ? null : contractFor(a)))
  .filter((c) => c && c.slug !== self)
  .map((c) => ({ slug: c.slug, options: part.slot["x-options"] ?? null })));

/**
 * The Milo files for one contract of another system, plus a <slug>.tokens.css
 * holding every token it reaches.
 *
 * An atom on its own keeps every variant: nobody has said which it needs. A block
 * knows, because each slot says what it asks for, so its one stylesheet holds its
 * own rules and only those looks of each atom, and its tokens are what's left.
 */
function miloWithTokens(ir, slug, { manifest }) {
  const k = slug.toLowerCase();
  const adapt = tokenSubset(tokenFiles);
  const files = renderers.milo.files(ir, slug, { manifest, contractFor, system, adapt });
  const cssFile = Object.keys(files).find((f) => f.endsWith(`/${k}.css`));
  const used = new Set(adapt.used);
  const header = `/* ${ir.component.name}: only the tokens it reaches, generated by spec-dictionary. Do not edit.\n * Re-run: npm run specs:render -- --slug=${slug} --target=milo --system=${system.id} */\n`;
  if (ir.component.tier === "block") {
    // Every look each atom is asked for, through the atoms that compose atoms.
    const looks = new Map(), irs = new Map([[slug, ir]]);
    const queue = [slug];
    while (queue.length) {
      const s = queue.shift();
      for (const child of childSlots(irs.get(s), s)) {
        if (!irs.has(child.slug)) { irs.set(child.slug, miloBuild(child.slug)); queue.push(child.slug); }
        looks.set(child.slug, [...(looks.get(child.slug) ?? []), ...looksOf(child.options)]);
      }
    }
    const atoms = [...looks].map(([s, list]) => {
      const childAdapt = tokenSubset(tokenFiles);
      const childFiles = renderers.milo.files(trimToLooks(irs.get(s), list), s, { manifest, contractFor, system, adapt: childAdapt });
      childAdapt.used.forEach((n) => used.add(n));
      return childFiles[Object.keys(childFiles).find((f) => f.endsWith(`/${s}.css`))];
    });
    files[cssFile] = [`@import url('./${k}.tokens.css');`, files[cssFile], ...atoms].join("\n\n");
  } else {
    const direct = [...new Set(childSlots(ir, slug).map((c) => c.slug))];
    if (direct.length) files[cssFile] = `${direct.map((s) => `@import url('../../${s}/milo/${s}.css');`).join("\n")}\n\n${files[cssFile]}`;
  }
  files[`packages/spectrum2/out/${k}/milo/${k}.tokens.css`] = subsetCss(tokenFiles, used, { header }).css;
  return files;
}

if (!slugs.length) {
  console.error("usage: npm run specs:render -- --slug=<slug> [--target=lit|milo|all] [--check]\n       npm run specs:render -- --all");
  process.exit(2);
}

let failures = 0, written = 0, stale = [];
for (const slug of slugs) {
  try {
    const { ir } = buildOne(slug, system.id === "s2a" ? {} : buildOpts(system));
    // The manifest is already derived during the build; the Lit target renders
    // it rather than deciding story combinations a second time.
    const manifestPath = join(system.out, slug, "stories.manifest.json");
    const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, "utf8")) : null;

    const produced = [];
    for (const id of chosen) {
      // A design-only contract has no element for Storybook to mount.
      if (id === "upstream" && ir.anchors?.code?.importPath === "") continue;
      const files = id === "milo" && tokenFiles ? miloWithTokens(ir, slug, { manifest }) : renderers[id].files(ir, slug, { manifest, contractFor, system });
      for (const [rel, contents] of Object.entries(files)) {
        const file = resolve(ROOT, rel);
        if (has("check")) {
          const onDisk = existsSync(file) ? readFileSync(file, "utf8") : null;
          if (onDisk !== contents) stale.push(`${rel} (${onDisk === null ? "missing" : "differs from a fresh render"})`);
        } else {
          mkdirSync(dirname(file), { recursive: true });
          writeFileSync(file, contents);
          written++;
        }
        produced.push(`${id}:${rel.split("/").pop()}`);
      }
    }
    console.log(`${has("check") ? "CHECK" : "RENDER"} ${slug.padEnd(24)} ${chosen.join(" + ").padEnd(12)} ${produced.length} files`);
  } catch (err) {
    console.log(`ERROR  ${slug}: ${err.message}`);
    failures++;
  }
}

if (has("check") && stale.length) {
  console.log(`\nSTALE — re-run without --check:`);
  for (const s of stale) console.log(`  ${s}`);
  process.exit(1);
}
console.log(has("check") ? `\n${slugs.length} checked, all fresh.` : `\n${written} files written for ${slugs.length} component(s).`);
process.exit(failures ? 1 : 0);
